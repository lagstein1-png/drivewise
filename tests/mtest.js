'use strict';

const ROOT = require('path').resolve(__dirname, '..');
const { forSpeech } = require(ROOT + '/tools/speech');
const { collect } = require(ROOT + '/tools/bank');

let pass = 0, fail = 0;
const is = (name, text, expect) => {
  const got = forSpeech(text);
  const ok = got.includes(expect);
  console.log((ok ? '✓ ' : '✗ ') + name);
  if(!ok) console.log('    ציפיתי ל: ' + expect + '\n    קיבלתי  : ' + got.slice(0, 76));
  ok ? pass++ : fail++;
};

/* ---- סמיכות ---- */
is('מפגש מסילת → נסמך',
   'האט לפני מפגש מסילת הברזל.', 'מִפְגַּשׁ');
is('למפגש מסילת → נסמך עם למ"ד שווא',
   'התקרבות למפגש מסילת ברזל.', 'לְמִפְגַּשׁ');
is('במפגש מסילת → נסמך עם בי"ת שווא',
   'מותר להמשיך במפגש מסילת ברזל?', 'בְּמִפְגַּשׁ');
is('מפגש רכבת → נסמך גם לפני "רכבת"',
   'לפני מפגש רכבת יש להאט.', 'מִפְגַּשׁ');

/* ---- נפרד ---- */
is('מפגש אפשרי → נפרד',
   'האט לקראת מפגש אפשרי עם רוכבי אופניים.', 'מִפְגָּשׁ');
is('המפגש מיודע → נפרד',
   'עצור לפני המפגש עד שהרכבת תחלוף.', 'הַמִּפְגָּשׁ');
is('כשהמפגש מיודע → נפרד',
   'כשהמפגש פנוי אפשר לחצות.', 'כְּשֶׁהַמִּפְגָּשׁ');
is('מהמפגש מיודע → נפרד',
   'כלי רכב המתרחקים מהמפגש.', 'מֵהַמִּפְגָּשׁ');

/* ---- שתי הצורות באותו משפט ---- */
{
  const t = forSpeech('התקרבות למפגש מסילת ברזל – כ-250 מטרים לפני המפגש.');
  const ok = t.includes('לְמִפְגַּשׁ') && t.includes('הַמִּפְגָּשׁ');
  console.log((ok ? '✓ ' : '✗ ') + 'שתי הצורות במשפט אחד');
  if(!ok) console.log('    ' + t);
  ok ? pass++ : fail++;
}

/* ---- מראה, החוקים הוותיקים ---- */
is('המראה של רכב → נקבה',
   'כיוון נכון של המראה השמאלית.', 'הַמַּרְאָה');
is('המראה במובן נוף → זכר',
   'את המראה הנשקף מאחור.', 'הַמַּרְאֶה');
is('ברירת מחדל → סמיכות',
   'זוהי ברירת המחדל.', 'בְּרֵירַת');

/* ---- כיסוי: כל המאגר, בלי קריסה ---- */
{
  const list = collect('he');
  let threw = null;
  for(const x of list){
    try{ forSpeech(x.text); }
    catch(e){ threw = x.text.slice(0, 50) + ' — ' + e.message; break; }
  }
  console.log((threw ? '✗ ' : '✓ ') + 'forSpeech עובר על כל ' + list.length.toLocaleString() + ' המחרוזות בלי לזרוק');
  if(threw) console.log('    ' + threw);
  threw ? fail++ : pass++;

  const smich = list.filter(x => /מִפְגַּשׁ/.test(forSpeech(x.text))).length;
  const ok = smich >= 55;
  console.log((ok ? '✓ ' : '✗ ') + 'צורת הנסמך חלה על ' + smich + ' מחרוזות במאגר');
  ok ? pass++ : fail++;
}

console.log('\n' + pass + ' עברו, ' + fail + ' נכשלו');
process.exit(fail ? 1 : 0);
