'use strict';

const { applyNumbers } = require('./number-rules');
const { applyContext } = require('./context-rules');
const { applyWords }   = require('./word-rules');
const { applyKtiv }    = require('./ktiv');

function forSpeech(text){
  let out = String(text == null ? '' : text);
  out = applyNumbers(out);
  out = applyContext(out);
  out = applyWords(out);
  out = applyKtiv(out);
  return out;
}

/* גיבוב קצר של הטקסט הנשלח למנוע. משמש את המניפסט כדי לדעת אילו
   קבצים הוקלטו עם איזו גרסה של החוקים — זה מה שמאפשר בנייה
   דיפרנציאלית במקום לבנות מחדש את כל מה שהחוקים נוגעים בו. */
function speechHash(text){
  const s = forSpeech(text);
  let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for(let i = 0; i < s.length; i++){
    const c = s.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 2654435761);
    h2 = Math.imul(h2 ^ c, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36);
}

module.exports = { forSpeech, speechHash };
