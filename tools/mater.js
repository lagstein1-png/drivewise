/* =====================================================================
   תאוריה מדברת · אימות קריאה — העברת התנועה אל האות שנושאת אותה
   כלי פיתוח. אפס תלויות.

   הנקדן מחזיר ניקוד בכתיב חסר גם כשהטקסט כתוב מלא. במקום לוותר על
   הווי"ו הוא משאיר אותה במקומה, שם את התנועה על האות שלפניה, ומסמן
   את הווי"ו במֶתֶג — "זו אֵם קריאה, לא עיצור":

     צֹוֽמֶת     במקום  צוֹמֶת
     מֻוֽתָּר     במקום  מוּתָּר

   זו נוטציה בלשנית. מנוע הקראה לא מכיר אותה, רואה וי"ו בלי תנועה,
   והוגה אותה כעיצור — ואת המתג הוא מפרש כהטעמה. הטעמה מלעילית
   ועיצור טפילי ביחד נשמעים כמו עברית במבטא אשכנזי כבד. זה בדיוק
   מה שקרה בסבב ההקלטה הראשון של הניקוד המלא.

   כאן מזיזים את התנועה אל אֵם הקריאה עצמה, ומקבלים כתיב מלא מנוקד
   תקני — הצורה שכל טקסט עברי מודרני משתמש בה:

     צ + חולם + ו + מתג   ←   צ + ו + חולם
     מ + קובוץ + ו + מתג  ←   מ + ו + דגש          (שורוק)

   *** האילוץ נשמר ***
   אף אות אינה נוספת, נמחקת או מוחלפת. רק סימנים זזים, והמתג יורד.
   לכן raw === stripNikud(pointed) ממשיך להתקיים בדיוק.
   ===================================================================== */
'use strict';

const LETTER = 'א-ת';
const HOLAM  = 'ֹ';
const KUBUTZ = 'ֻ';
const DAGESH = 'ּ';
const VAV    = 'ו';
const METEG  = 'ֽ';
const MARK   = '֑-ׇ';

/* אות, הסימנים שעליה, וי"ו, ומתג שמסמן אותה כאֵם קריאה */
const MATER = new RegExp(
  '([' + LETTER + '])([' + MARK + ']*)' + VAV + METEG, 'g');

function fixMaters(text){
  let out = String(text == null ? '' : text).replace(MATER, (m, letter, marks) => {
    if(marks.indexOf(HOLAM) !== -1){
      /* חולם מלא: התנועה עוברת אל הווי"ו */
      return letter + marks.split(HOLAM).join('') + VAV + HOLAM;
    }
    if(marks.indexOf(KUBUTZ) !== -1){
      /* שורוק: הקובוץ הופך לנקודה בתוך הווי"ו */
      return letter + marks.split(KUBUTZ).join('') + VAV + DAGESH;
    }
    /* וי"ו שאינה נושאת תנועה — רק המתג יורד */
    return letter + marks + VAV;
  });

  /* מתגים שנותרו מסמנים הטעמה משנית. הם נדירים בטקסט מודרני, המנוע
     לא נתקל בהם באימון, והם מזיזים את ההטעמה. יורדים כולם. */
  out = out.split(METEG).join('');

  return out.normalize('NFC');
}

module.exports = { fixMaters };
