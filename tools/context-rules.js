function ruleToRegex(rule){
  let src = B0 + '(' + rule.word + ')' + B1;
  if(rule.after)  src += '(\\s+' + rule.after + ')';
  let re = src;
  if(rule.before) re = B0 + rule.before + B1 + '(\\s+\\S*\\s*)?' + '(' + rule.word + ')' + B1
                     + (rule.after ? '(\\s+' + rule.after + ')' : '');
  return new RegExp(re, 'g');
}

/* מחיל את החוקים. מחזיר גם דיווח, כדי שאפשר יהיה לבדוק מה נגע במה. */
function applyContext(text, opts){
  const report = [];
  let out = String(text == null ? '' : text);

  for(const rule of CONTEXT_RULES){
    if(rule.before){
      /* המילה שלפני נבדקת במבט לאחור, ולכן ההתאמה כולה היא המילה
         המנוקדת עצמה — ואפשר פשוט להחזיר את הניקוד.

         קודם היה כאן צירוף של קבוצות והחזרה לפי מיקומן. זה נשבר
         ברגע שהופיע חוק before ראשון: rule.before מכיל קבוצות
         משלו, המספור זז, והארגומנט שנחשב ל"סיומת" היה בעצם המיקום
         במחרוזת — כך נולד "קְדִימָה2". מבט לאחור לא סופר קבוצות. */
      /* המרווח הוא כל רצף שאינו עברית, ולא רווח בלבד. האפליקציה
         מהלכת על אסימונים ולכן "ישר (קדימה)" הוא אצלה שכנות מלאה;
         דרישת רווח כאן הייתה מפצלת את שני המסלולים בדיוק שם. */
      const re = new RegExp(
        '(?<=(?:^|' + NOT_HE + ')(?:' + rule.before + ')' + B1 + NOT_HE + '+)' +
        '(?:' + rule.word + ')' + B1 +
        (rule.after ? '(?=' + NOT_HE + '+(?:' + rule.after + ')' + B1 + ')' : ''), 'g');
      out = out.replace(re, () => {
        report.push(rule.why);
        return rule.voweled;
      });
    } else {
      const re = new RegExp(
        B0 + '(' + rule.word + ')' + B1 +
        (rule.after ? '(\\s+' + rule.after + ')' : ''), 'g');
      out = out.replace(re, (m, pre, word, tail) => {
        report.push(rule.why);
        return pre + rule.voweled + (tail || '');
      });
    }
  }

  if(opts && opts.report) return { text: out, applied: report };
  return out;
}

