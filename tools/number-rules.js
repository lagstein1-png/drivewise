'use strict';

const HE_DIGIT = ['אפס', 'אחת', 'שתיים', 'שלוש', 'ארבע', 'חמש', 'שש', 'שבע', 'שמונה', 'תשע'];

/* יחידות מידה שמופיעות במאגר. מספר שצמוד לאחת מהן הוא כמות גם אם
   הוא לבדו במחרוזת — "90 קמ"ש" למשל. */
const UNITS = [
  'קמ"ש', 'קמ״ש', 'קמש',
  'ק"מ', 'ק״מ',
  'מטרים', 'מטר', 'מ\'', 'מ׳',
  'ס"מ', 'ס״מ', 'סנטימטרים',
  'טון', 'ק"ג', 'ק״ג', 'קילוגרם',
  'שניות', 'שנייה', 'דקות', 'דקה', 'שעות', 'שעה',
  'שנים', 'שנה', 'חודשים', 'חודש',
  'אחוז', 'אחוזים', '%'
];

/* מספר בן 3 ספרות ומעלה. דו-ספרתי נשאר כמות — "50" הוא כמעט תמיד
   מהירות או מרחק, לא מספר תמרור. */
const MIN_DIGITS = 3;

/* האם המחרוזת כולה מספר, בלי אות ובלי יחידה? */
function isBareNumber(text){
  const t = String(text == null ? '' : text).trim();
  if(!new RegExp('^\\d{' + MIN_DIGITS + ',}$').test(t)) return false;
  return true;
}

/* האם ליד המספר יש יחידת מידה? נבדק על המחרוזת כולה, כדי שגם
   "90 קמ\"ש" לבדו לא ייקרא ספרה-ספרה. */
function hasUnit(text){
  const t = String(text == null ? '' : text);
  return UNITS.some(u => t.indexOf(u) !== -1);
}

function spellDigits(digits){
  return String(digits).split('').map(d => HE_DIGIT[+d]).join(' ');
}

/* נקודת הכניסה. מחזיר את הטקסט כפי שיש לשלוח למנוע. */
function applyNumbers(text){
  const t = String(text == null ? '' : text);
  if(hasUnit(t)) return t;          /* כמות עם יחידה — לא נוגעים */
  if(!isBareNumber(t)) return t;    /* מספר בתוך משפט — כמות */
  return spellDigits(t.trim());
}

module.exports = { applyNumbers, isBareNumber, hasUnit, spellDigits, HE_DIGIT, UNITS, MIN_DIGITS };
